// while, em quanto for verdade
// 1° verifoca depois executa
// não se sabe quantas vezes pode repetir
// exemplo, enquanto o usuário não digitar sair, continua rodando
// deve ter uma condição para sair do laço ou entra no loop

let conta = 60

while(conta != 0){
    console.log(`${conta} / 5 = ${conta/5}`)
    conta -= 5
}